// 광역 별칭 정규화
const ALIAS: Record<string, string> = {
  '서울특별시': '서울',
  '경기도':     '경기',
  '인천광역시': '인천',
}

function getCoords(region: string): readonly [number, number] | null {
  const key = ALIAS[region] ?? region
  return COORDS[key] ?? null
}

function haversineKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371
  const dLat = (lat2 - lat1) * Math.PI / 180
  const dLon = (lon2 - lon1) * Math.PI / 180
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
    Math.sin(dLon / 2) ** 2
  return R * 2 * Math.asin(Math.sqrt(a))
}

/** 30km 이내 → +2, 초과 또는 좌표 없음 → 0 */
export function getRegionScore(r1: string, r2: string): number {
  const c1 = getCoords(r1)
  const c2 = getCoords(r2)
  if (!c1 || !c2) return 0
  return haversineKm(c1[0], c1[1], c2[0], c2[1]) <= 30 ? 2 : 0
}

